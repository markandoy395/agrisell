type FarmProfile = {
  farmName: string;
  farmLocation: string;
  gpsLat: number;
  gpsLong: number;
  totalCrops: number;
  farmSizeHectares: number;
  farmingType: string;
  soilType: string;
  irrigationType: string;
  mainCrops: string[];
  certifications: string[];
  commodities: string[];
  accentColor?: string;
  backgroundColor?: string;
  status?: string;
  tone?: string;
};

type FarmerFarmGroup = {
  farmerId: string;
  idPrefix: string;
  defaultAccentColor: string;
  defaultBackgroundColor: string;
  defaultStatus: string;
  defaultTone: string;
  profiles: FarmProfile[];
};

const buildFarmerFarm = (
  group: FarmerFarmGroup,
  profile: FarmProfile,
  index: number,
): FarmerFarm => {
  const farmImageOffset = group.idPrefix.length + index;

  return {
    id: `${group.idPrefix}-${index + 1}`,
    farmerId: group.farmerId,
    farmName: profile.farmName,
    farmLocation: profile.farmLocation,
    gpsLat: profile.gpsLat,
    gpsLong: profile.gpsLong,
    totalCrops: profile.totalCrops,
    farmSizeHectares: profile.farmSizeHectares,
    farmingType: profile.farmingType,
    soilType: profile.soilType,
    irrigationType: profile.irrigationType,
    mainCrops: profile.mainCrops,
    certifications: profile.certifications,
    commodities: profile.commodities,
    farmImages: [
      {
        title: "Farm overview",
        alt: `Sample farm photo for ${profile.farmName}`,
        imageUrl: getSampleFarmImageUrl(farmImageOffset, 0),
      },
      {
        title: "Production area",
        alt: `Sample production area photo for ${profile.farmName}`,
        imageUrl: getSampleFarmImageUrl(farmImageOffset, 1),
      },
      {
        title: "Harvest section",
        alt: `Sample harvest photo for ${profile.farmName}`,
        imageUrl: getSampleFarmImageUrl(farmImageOffset, 2),
      },
      {
        title: "Irrigation setup",
        alt: `Sample irrigation photo for ${profile.farmName}`,
        imageUrl: getSampleFarmImageUrl(farmImageOffset, 3),
      },
      {
        title: "Packing area",
        alt: `Sample packing area photo for ${profile.farmName}`,
        imageUrl: getSampleFarmImageUrl(farmImageOffset, 4),
      },
    ],
    status: profile.status ?? group.defaultStatus,
    tone: profile.tone ?? group.defaultTone,
  };
};

